"""Column alignment for full-LLM runs (RQ2).

When the schema is generated by the LLM, table/column names may diverge from
the gold-standard schema while remaining semantically equivalent. The cell-level
evaluator requires a correspondence between the generated database and the gold
schema (docs/11 section 6.4). This module builds that correspondence:

1. exact normalised-name match (case-fold, snake-case, singular/plural);
2. fallback to a per-dataset alias registry mapping generated column names to
   gold column names (validated by the research team, versioned per dataset).

Tables are aligned by normalised name first; a table that cannot be matched is
excluded from the cell-level comparison and reported as ``unmatched_tables``.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.models.schema_models import NormalizedSchema


def normalise_name(name: str) -> str:
    """Lower-case, snake-case and singular/plural-normalise a name."""
    normalised = "".join(ch if ch.isalnum() else "_" for ch in name.lower())
    normalised = "_".join(part for part in normalised.split("_") if part)
    if normalised.endswith("ies"):
        normalised = normalised[:-3] + "y"
    elif normalised.endswith("s") and not normalised.endswith("ss"):
        normalised = normalised[:-1]
    return normalised


def match_table(gold_table: Any, generated_tables: list[str]) -> str | None:
    target = normalise_name(gold_table.name)
    candidates = [(normalise_name(name), name) for name in generated_tables]
    for candidate, name in candidates:
        if candidate == target:
            return name
    for candidate, name in candidates:
        if len(candidate) >= 3 and len(target) >= 3 \
                and (target in candidate or candidate in target):
            return name
    return None


def load_alias_registry(dataset_dir: Path) -> dict:
    """Load ``column_alias.json`` from a dataset directory if present.

    Format: {generated_table: {generated_column: gold_column}}
    """
    path = dataset_dir / "column_alias.json"
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def inspect_generated_tables(conn) -> dict[str, list[str]]:
    """Return {table_name: [column names]} for a generated SQLite database."""
    tables: dict[str, list[str]] = {}
    cursor = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
    )
    for (name,) in cursor.fetchall():
        cols = [row[1] for row in conn.execute(f"PRAGMA table_info([{name}])")]
        tables[name] = cols
    return tables


def build_alignment(schema: NormalizedSchema, generated_conn,
                    registry: dict | None = None) -> dict:
    """Map each gold table to its generated counterpart and columns.

    Returns:
    {
        "tables": {gold_table: generated_table},
        "columns": {gold_table: {gold_column: generated_column}},
        "unmatched_tables": [gold_table, ...],
        "unmatched_columns": {gold_table: [gold_column, ...]},
        "via_registry": [{"table", "gold_column", "generated_column"}, ...],
    }
    """
    registry = registry or {}
    generated_tables = inspect_generated_tables(generated_conn)
    result: dict = {
        "tables": {}, "columns": {}, "unmatched_tables": [],
        "unmatched_columns": {}, "via_registry": [],
    }

    for gold_table in schema.tables:
        generated_name = match_table(gold_table, list(generated_tables.keys()))
        if generated_name is None:
            result["unmatched_tables"].append(gold_table.name)
            continue
        result["tables"][gold_table.name] = generated_name
        generated_columns = generated_tables[generated_name]
        registry_map = registry.get(generated_name, {})
        column_map: dict[str, str] = {}
        for column in gold_table.columns:
            target = normalise_name(column.name)
            matched = next(
                (name for name in generated_columns
                 if normalise_name(name) == target),
                None,
            )
            if matched is None:
                matched = next(
                    (name for name in generated_columns
                     if len(target) >= 3 and len(normalise_name(name)) >= 3
                     and (target in normalise_name(name)
                          or normalise_name(name) in target)),
                    None,
                )
            if matched is None and column.name in registry_map:
                matched = registry_map[column.name]
            if matched is not None and matched in generated_columns:
                column_map[column.name] = matched
                if column.name != matched and column.name in registry_map:
                    result["via_registry"].append({
                        "table": gold_table.name,
                        "gold_column": column.name,
                        "generated_column": matched,
                    })
            else:
                result["unmatched_columns"].setdefault(gold_table.name, []).append(column.name)
        result["columns"][gold_table.name] = column_map

    return result
