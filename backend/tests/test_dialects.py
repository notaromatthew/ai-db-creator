import sqlite3

import pytest

from app.core.db_export import SUPPORTED_DIALECTS, export_full
from app.core.db_generator import create_database_from_schema
from app.models.schema_models import ColumnDef, NormalizedSchema, TableDef

from schema_factories import valid_schema


@pytest.fixture()
def exported(tmp_path):
    schema = valid_schema()
    schema.tables[0].columns.append(ColumnDef(name="nascita", data_type="DATE"))
    schema.tables[0].columns.append(ColumnDef(name="attivo", data_type="BOOLEAN"))
    schema.tables[1].columns.append(ColumnDef(name="sigla", data_type="VARCHAR(10)", is_not_null=True, default_value="n/d"))
    path = str(tmp_path / "db.sqlite")
    create_database_from_schema(schema, path)
    con = sqlite3.connect(path)
    con.execute("INSERT INTO autori (id, nome, nascita, attivo) VALUES (1, 'O''Hara', '1990-05-17', 1)")
    con.execute("INSERT INTO libri (id, titolo, autore_id, sigla) VALUES (1, 'Dune', 1, 'DU')")
    con.commit()
    con.close()
    return {dialect: export_full(dialect, path, schema) for dialect in SUPPORTED_DIALECTS}


def test_supported_dialects_include_oracle():
    assert SUPPORTED_DIALECTS == ("sqlite", "postgresql", "mysql", "mssql", "oracle")


def test_sqlite_export(exported):
    sql = exported["sqlite"]
    assert "id INTEGER PRIMARY KEY" in sql and "nome TEXT" in sql and "nascita TEXT" in sql
    assert "DROP TABLE" not in sql
    assert "'O''Hara'" in sql
    assert "FOREIGN KEY (autore_id) REFERENCES autori(id)" in sql


def test_postgresql_export(exported):
    sql = exported["postgresql"]
    assert "DROP TABLE IF EXISTS libri;" in sql and sql.index("DROP TABLE IF EXISTS libri") < sql.index("DROP TABLE IF EXISTS autori")
    assert "nascita DATE" in sql and "attivo BOOLEAN" in sql and "sigla VARCHAR(10)" in sql
    assert "INSERT INTO autori (id, nome, nascita, attivo)" in sql


def test_mysql_export(exported):
    sql = exported["mysql"]
    assert "id INT PRIMARY KEY" in sql and "attivo TINYINT(1)" in sql and "nome TEXT" in sql
    assert "DROP TABLE IF EXISTS autori;" in sql


def test_mssql_export(exported):
    sql = exported["mssql"]
    assert "nome NVARCHAR(MAX)" in sql and "attivo BIT" in sql and "sigla NVARCHAR(10)" in sql
    assert "CONSTRAINT FK_libri_autore_id FOREIGN KEY" in sql


def test_oracle_types_identity_and_no_if_exists(exported):
    sql = exported["oracle"]
    assert "id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "PRIMARY KEY" in sql
    assert "nome CLOB" in sql and "titolo CLOB" in sql
    assert "sigla VARCHAR2(10) DEFAULT 'n/d' NOT NULL" in sql
    assert "nascita DATE" in sql and "attivo NUMBER(1)" in sql
    assert "autore_id NUMBER(10)" in sql
    assert "IF NOT EXISTS" not in sql and "IF EXISTS" not in sql
    assert "FOREIGN KEY (autore_id) REFERENCES autori(id)" in sql
    assert "VARCHAR2(10)" in sql and "NVARCHAR" not in sql


def test_oracle_drops_tables_with_exception_block_in_reverse_order(exported):
    sql = exported["oracle"]
    assert "EXECUTE IMMEDIATE 'DROP TABLE libri CASCADE CONSTRAINTS'" in sql
    assert sql.index("DROP TABLE libri") < sql.index("DROP TABLE autori")
    assert "SQLCODE != -942" in sql


def test_oracle_data_uses_typed_date_literals_and_escaped_strings(exported):
    sql = exported["oracle"]
    assert "DATE '1990-05-17'" in sql
    assert "'O''Hara'" in sql
    assert "INSERT INTO libri (id, titolo, autore_id, sigla) VALUES (1, 'Dune', 1, 'DU');" in sql


def test_oracle_text_keys_become_varchar2(tmp_path):
    schema = NormalizedSchema(tables=[TableDef(name="paesi", columns=[
        ColumnDef(name="codice", data_type="TEXT", is_primary_key=True),
        ColumnDef(name="nome", data_type="TEXT", is_unique=True),
    ])], relationships=[])
    path = str(tmp_path / "p.sqlite")
    create_database_from_schema(schema, path)
    sql = export_full("oracle", path, schema)
    assert "codice VARCHAR2(255)" in sql and "nome VARCHAR2(255) UNIQUE" in sql and "CLOB" not in sql


def test_target_dialect_is_remembered_per_project_and_used_by_export(client, project):
    c, _ = client
    pid = project["id"]
    sql = b"CREATE TABLE persone (id INTEGER PRIMARY KEY, nome TEXT);"
    c.post(f"/api/projects/{pid}/import-sql?dialect=sqlite", files={"file": ("s.sql", sql, "text/sql")})
    assert c.get(f"/api/projects/{pid}").json()["target_dialect"] is None
    assert c.put(f"/api/projects/{pid}/dialect", json={"dialect": "db2"}).status_code == 422
    assert c.put(f"/api/projects/{pid}/dialect", json={"dialect": "oracle"}).json() == {"target_dialect": "oracle"}
    assert c.get(f"/api/projects/{pid}").json()["target_dialect"] == "oracle"
    exported = c.get(f"/api/projects/{pid}/export-full").json()
    assert exported["format"] == "oracle" and "CLOB" in exported["content"]
    assert c.get(f"/api/projects/{pid}/export-full?dialect=mysql").json()["format"] == "mysql"
    assert c.get(f"/api/projects/{pid}/export-full?dialect=db2").status_code == 422
    other = c.post("/api/projects", json={"name": "B"}).json()["id"]
    assert c.get(f"/api/projects/{other}").json()["target_dialect"] is None


def test_viewer_cannot_change_dialect(client, project):
    from test_schema_versions import as_user
    c, _ = client
    pid = project["id"]
    as_user("viewer", "v@example.com")
    c.get("/api/me")
    as_user("test-user", "owner@example.com")
    c.post(f"/api/projects/{pid}/invites", json={"email": "v@example.com", "role": "viewer"})
    as_user("viewer", "v@example.com")
    assert c.put(f"/api/projects/{pid}/dialect", json={"dialect": "oracle"}).status_code == 403
