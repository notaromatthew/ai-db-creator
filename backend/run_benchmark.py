"""Batch benchmark runner for RQ1/RQ2 (docs/11, section 7).

Runs each benchmark dataset across experimental conditions and repeated runs,
driving the real domain services (schema generation, population) so that every
run produces a fresh project, an isolated SQLite database and a cell-level
evaluation report against the dataset's ground truth.

Usage:
    python run_benchmark.py \
        --datasets university,library,hospital \
        --conditions full_llm,baseline \
        --runs 3 \
        --output reports/benchmark

Optional:
    --adjudicate  run the supplementary LLM-as-judge comparison (schema
                  equivalence / value accuracy / completeness at temperature 0)
                  and record the scores next to the deterministic metrics.
    --temperature FLOAT  LLM sampling temperature for schema generation and
                  population. Defaults to the pipeline defaults (0.1). Use
                  0.0/0.1 for byte-for-byte reproducibility across runs; raise
                  (e.g. 0.5) to sample the run-to-run LLM distribution so the
                  mean/CI over runs reflects genuine output variability. The
                  adjudication judge always runs at 0.0.

Conditions:
    full_llm : schema generated by the LLM from source documents, then
               populated by the LLM.
    baseline : gold-standard schema applied deterministically, then populated
               by the LLM (isolates population quality from schema generation).

Aggregation:
    For each (dataset, condition) a summary CSV and JSON report is written
    listing per-run primary and strict F1 / precision / recall next to
    descriptive means. No Wilson interval is reported for F1 or mean-run F1.
"""
from __future__ import annotations

import argparse
import asyncio
import csv
import json
import os
import subprocess
import sys
from pathlib import Path

from app.models.schema_models import GenerateRequest
from app.utils.research import atomic_write_json, sha256_file, sha256_text, stable_hash


def round_or_none(value, ndigits: int = 4):
    if value is None:
        return None
    return round(float(value), ndigits)

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASETS_DIR = REPO_ROOT / "data" / "datasets"


def software_revision() -> dict:
    configured = os.getenv("SOFTWARE_REVISION")
    if configured:
        return {"value": configured, "source": "SOFTWARE_REVISION"}
    try:
        value = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, check=True,
            capture_output=True, text=True, timeout=3,
        ).stdout.strip()
        if value:
            return {"value": value, "source": "git"}
    except (OSError, subprocess.SubprocessError):
        pass
    return {"value": None, "source": "unavailable"}


class BenchmarkRunner:
    def __init__(self, datasets: list[str], conditions: list[str], runs: int,
                 output_dir: Path, parallel: int = 1, adjudicate: bool = False,
                 temperature: float | None = None):
        self.datasets = datasets
        self.conditions = conditions
        self.runs = runs
        self.output_dir = output_dir
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.parallel = parallel
        self.adjudicate = adjudicate
        self.temperature = temperature
        from app.services.schema_service import SchemaService
        from app.services.document_service import DocumentService
        from app.services.population_service import PopulationService
        self.schema_svc = SchemaService()
        self.doc_svc = DocumentService()
        self.pop_svc = PopulationService()

    # ------------------------------------------------------------------ utils
    @staticmethod
    def _source_files(dataset: str) -> list[Path]:
        source = DATASETS_DIR / dataset / "source"
        if not source.exists():
            return []
        return sorted([p for p in source.iterdir() if p.is_file()])

    @staticmethod
    def _gold_schema(dataset: str) -> Path:
        return DATASETS_DIR / dataset / "gold_schema.json"

    @staticmethod
    def _ground_truth(dataset: str) -> Path:
        return DATASETS_DIR / dataset / "ground_truth.db"

    @staticmethod
    def _label(dataset: str) -> str:
        return dataset

    @staticmethod
    def _prompt(dataset: str) -> str:
        with (DATASETS_DIR / dataset / "prompt.txt").open("r", encoding="utf-8") as fh:
            return fh.read().strip()

    # ------------------------------------------------------------- per project
    async def _create_populated_project(self, dataset: str, condition: str,
                                        run_index: int) -> str:
        from app.models.database import init_db
        init_db()
        project = self.schema_svc.create_project(
            name=f"{dataset}|{condition}|run{run_index}",
            prompt=self._prompt(dataset),
        )
        project_id = project.id

        uploaded = []
        for src in self._source_files(dataset):
            doc = self.doc_svc.upload_document(project_id, str(src), original_filename=src.name)
            uploaded.append(doc.id)

        if condition == "full_llm":
            request = GenerateRequest(
                prompt=self._prompt(dataset),
                document_ids=uploaded,
                condition=condition,
                session_id=f"{dataset}-{condition}-run{run_index}",
            )
            await self.schema_svc.generate_from_prompt(project_id, request,
                                                       temperature=self.temperature)
        elif condition == "baseline":
            from app.models.schema_models import NormalizedSchema
            gold = json.loads(self._gold_schema(dataset).read_text(encoding="utf-8"))
            self.schema_svc.update_schema(project_id, NormalizedSchema(**gold))
        else:
            raise ValueError(f"Unknown condition: {condition}")

        project = self.schema_svc.get_project(project_id)
        schema = self.schema_svc.get_schema(project_id)
        await self.pop_svc.populate(project_id, project.db_path, schema, uploaded,
                                    temperature=self.temperature)
        return project_id

    def _evaluate(self, project_id: str, dataset: str, condition: str,
                  alignment: dict | None = None):
        from app.evaluation.population_evaluation import (
            connect_database, evaluate_generated, load_gold_schema, read_rows,
        )
        from app.evaluation.canonical_facts import evaluate_canonical_facts
        from app.evaluation.schema_alignment import load_alignment_config
        project = self.schema_svc.get_project(project_id)
        schema = load_gold_schema(str(self._gold_schema(dataset)))
        column_aliases = (alignment or {}).get("columns") or None
        table_aliases = (alignment or {}).get("tables") or None
        config = load_alignment_config(DATASETS_DIR / dataset)
        generated_rows = {}
        ground_rows = {}
        with connect_database(project.db_path) as generated, \
                connect_database(str(self._ground_truth(dataset))) as ground:
            strict = evaluate_generated(generated, ground, schema, column_aliases, table_aliases)
            primary = evaluate_canonical_facts(generated, ground, schema, config, condition)
            for table in schema.tables:
                aliases = (column_aliases or {}).get(table.name, {})
                generated_rows[table.name] = read_rows(
                    generated, table, aliases, (table_aliases or {}).get(table.name)
                )
                ground_rows[table.name] = read_rows(ground, table)
        return project, {"primary": primary, "supplementary_strict": strict}, generated_rows, ground_rows

    def _build_alignment(self, project_id: str, dataset: str) -> dict | None:
        from app.evaluation.schema_alignment import (
            build_alignment, load_alias_registry,
        )
        from app.evaluation.population_evaluation import connect_database, load_gold_schema
        project = self.schema_svc.get_project(project_id)
        schema = load_gold_schema(str(self._gold_schema(dataset)))
        registry = load_alias_registry(DATASETS_DIR / dataset)
        with connect_database(project.db_path) as generated:
            return build_alignment(schema, generated, registry)

    async def _run_one(self, dataset: str, condition: str, run_index: int) -> dict:
        record = {
            "dataset": dataset, "condition": condition, "run": run_index,
            "project_id": None, "status": "ok",
            "temperature": self.temperature,
            "primary_precision": None, "primary_recall": None, "primary_f1": None,
            "strict_precision": None, "strict_recall": None, "strict_f1": None,
            "total_cells": None, "missing_rows": None, "extra_rows": None,
            "alignment": None, "evaluation": None, "adjudication": None,
            "provenance": None, "error": None,
        }
        run_dir = self.output_dir / dataset / condition
        run_dir.mkdir(parents=True, exist_ok=True)
        try:
            project_id = await self._create_populated_project(dataset, condition, run_index)
            alignment = self._build_alignment(project_id, dataset) \
                if condition == "full_llm" else None
            project, result, generated_rows, ground_rows = \
                self._evaluate(project_id, dataset, condition, alignment)
            primary = result["primary"]
            strict = result["supplementary_strict"]
            record.update({
                "project_id": project_id,
                "primary_precision": round_or_none(primary.get("global", {}).get("precision")),
                "primary_recall": round_or_none(primary.get("global", {}).get("recall")),
                "primary_f1": round_or_none(primary.get("global", {}).get("f1")),
                "strict_precision": round_or_none(strict["global"]["precision"]),
                "strict_recall": round_or_none(strict["global"]["recall"]),
                "strict_f1": round_or_none(strict["global"]["f1"]),
                "total_cells": strict["global"]["total_cells"],
                "missing_rows": strict["global"]["missing_rows"],
                "extra_rows": strict["global"]["extra_rows"],
                "evaluation": result,
                "provenance": {
                    "prompt_sha256": sha256_text(self._prompt(dataset)),
                    "gold_schema_sha256": sha256_file(self._gold_schema(dataset)),
                    "ground_truth_sha256": sha256_file(self._ground_truth(dataset)),
                    "generated_schema_sha256": stable_hash(self.schema_svc.get_schema(project_id).model_dump()),
                    "generated_db_sha256": sha256_file(project.db_path),
                    "source_sha256": {path.name: sha256_file(path) for path in self._source_files(dataset)},
                    "alignment_config_hash": primary.get("config_hash"),
                    "evaluator_version": primary.get("evaluator_version"),
                    "software_revision": software_revision(),
                },
            })
            if alignment is not None:
                record["alignment"] = {
                    "tables": alignment["tables"],
                    "columns": alignment["columns"],
                    "unmatched_tables": alignment["unmatched_tables"],
                    "unmatched_columns": alignment["unmatched_columns"],
                    "ambiguous_tables": alignment["ambiguous_tables"],
                    "ambiguous_columns": alignment["ambiguous_columns"],
                    "via_registry": alignment["via_registry"],
                    "method_version": alignment["method_version"],
                }
            if self.adjudicate:
                gold_schema = self._load_gold_schema(dataset)
                generated_schema = self.schema_svc.get_schema(project_id)
                from app.evaluation.llm_adjudication import adjudicate
                adjudication = await adjudicate(
                    gold_schema, generated_schema, ground_rows, generated_rows,
                )
                record["adjudication"] = adjudication
        except Exception as exc:
            record["status"] = "error"
            record["error"] = f"{type(exc).__name__}: {exc}"
        atomic_write_json(run_dir / f"run{run_index:02d}.json",
                          {**record, "detail": None})
        return record

    def _load_gold_schema(self, dataset: str):
        from app.evaluation.population_evaluation import load_gold_schema
        return load_gold_schema(str(self._gold_schema(dataset)))

    # ---------------------------------------------------------------- wrapper
    async def run(self) -> list[dict]:
        tasks = []
        for dataset in self.datasets:
            for condition in self.conditions:
                for run_index in range(1, self.runs + 1):
                    tasks.append(self._run_one(dataset, condition, run_index))
        sem = asyncio.Semaphore(self.parallel)
        async def guarded(task):
            async with sem:
                return await task
        results = [r for r in await asyncio.gather(*[guarded(t) for t in tasks],
                                                    return_exceptions=True)
                   if isinstance(r, dict)]
        for dataset in self.datasets:
            for condition in self.conditions:
                self._write_summary(dataset, condition, results)
        return results

    def _write_summary(self, dataset: str, condition: str,
                       all_records: list[dict]) -> None:
        records = [r for r in all_records
                   if r["dataset"] == dataset and r["condition"] == condition]
        records.sort(key=lambda r: r["run"])
        out = self.output_dir / dataset
        out.mkdir(parents=True, exist_ok=True)

        rows_path = out / f"{condition}.csv"
        fields = ["dataset", "condition", "run", "project_id",
                  "primary_precision", "primary_recall", "primary_f1",
                  "strict_precision", "strict_recall", "strict_f1",
                  "total_cells", "missing_rows", "extra_rows"]
        with rows_path.open("w", newline="", encoding="utf-8") as fh:
            writer = csv.DictWriter(fh, fieldnames=fields)
            writer.writeheader()
            for r in records:
                writer.writerow({k: r[k] for k in fields})

        summary = self._aggregate(records)
        summary_path = out / f"{condition}_summary.json"
        atomic_write_json(summary_path, summary)

    def _aggregate(self, records: list[dict]) -> dict:
        import statistics as stats
        def col(key: str) -> list[float]:
            return [r[key] for r in records if r[key] is not None]
        def mean(vals: list[float]) -> float | None:
            return round_or_none(stats.mean(vals)) if vals else None
        def adjudication_col(key: str) -> list[float]:
            return [r["adjudication"]["scores"][key] for r in records
                    if isinstance(r.get("adjudication"), dict)
                    and r["adjudication"].get("scores")
                    and r["adjudication"]["scores"].get(key) is not None]
        summary = {
            "dataset": records[0]["dataset"] if records else None,
            "condition": records[0]["condition"] if records else None,
            "n_runs": len(records),
            "temperature": records[0].get("temperature") if records else None,
            "reporting_status": "exploratory_descriptive",
            "mean_primary_precision": mean(col("primary_precision")),
            "mean_primary_recall": mean(col("primary_recall")),
            "mean_primary_f1": mean(col("primary_f1")),
            "mean_strict_f1": mean(col("strict_f1")),
            "mean_total_cells": mean([r["total_cells"] for r in records]),
            "mean_missing_rows": mean([r["missing_rows"] for r in records]),
            "mean_extra_rows": mean([r["extra_rows"] for r in records]),
        }
        for dimension in ("schema_equivalence", "value_accuracy", "completeness"):
            values = adjudication_col(dimension)
            summary[f"mean_adjudicated_{dimension}"] = mean(values)
        return summary


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Batch benchmark runner (RQ1/RQ2).")
    parser.add_argument("--datasets", default="university,library,hospital",
                        help="Comma-separated datasets under data/datasets/.")
    parser.add_argument("--conditions", default="full_llm,baseline",
                        help="Comma-separated conditions to run.")
    parser.add_argument("--runs", type=int, default=3, help="Runs per (dataset, condition).")
    parser.add_argument("--output", default="reports/benchmark",
                        help="Output directory for run reports and summaries.")
    parser.add_argument("--parallel", type=int, default=1,
                        help="Max concurrent projects (LLM calls run in parallel).")
    parser.add_argument("--adjudicate", action="store_true",
                        help="Run the dynamic LLM-as-judge comparison (supplementary "
                             "scores alongside the deterministic metrics).")
    parser.add_argument("--temperature", type=float, default=None,
                        help="LLM sampling temperature for schema generation and "
                             "population (defaults to the pipeline defaults: 0.1). "
                             "Keep 0.0/0.1 for byte-for-byte reproducibility; raise "
                             "(e.g. 0.5) to sample the run-to-run LLM distribution.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    datasets = [d.strip() for d in args.datasets.split(",") if d.strip()]
    conditions = [c.strip() for c in args.conditions.split(",") if c.strip()]
    runner = BenchmarkRunner(datasets, conditions, args.runs,
                             Path(args.output), parallel=args.parallel,
                             adjudicate=args.adjudicate,
                             temperature=args.temperature)
    results = asyncio.run(runner.run())
    ok_count = sum(result.get("status") == "ok" for result in results)
    error_count = sum(result.get("status") == "error" for result in results)
    print(json.dumps({
        "output": str(runner.output_dir),
        "n_runs": len(results),
        "ok": ok_count,
        "error": error_count,
        "temperature": runner.temperature,
    }, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
